fn legacy_title_action(packet: &CTitleLegacy, protocol: i32) -> i32 {
    let mut buf = Vec::new();
    packet.encode(&mut buf, ProtocolVersion(protocol)).unwrap();
    buf.as_slice().read_var_int().unwrap().0
}

#[test]
fn legacy_title_actions_shift_at_1_11() {
    let times = CTitleLegacy::SetTimes {
        fade_in: 1,
        stay: 2,
        fade_out: 3,
    };
    for (protocol, shift) in [
        (47, 0),
        (110, 0),
        (210, 0),
        (315, 1),
        (316, 1),
        (340, 1),
        (754, 1),
    ] {
        assert_eq!(
            legacy_title_action(&times, protocol),
            2 + shift,
            "times action at protocol {protocol}"
        );
        assert_eq!(
            legacy_title_action(&CTitleLegacy::Hide, protocol),
            3 + shift,
            "hide action at protocol {protocol}"
        );
        assert_eq!(
            legacy_title_action(&CTitleLegacy::Reset, protocol),
            4 + shift,
            "reset action at protocol {protocol}"
        );
    }
}
